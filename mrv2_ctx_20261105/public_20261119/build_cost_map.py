"""Build COST_MAP.md from committed raw outputs only.

  python build_cost_map.py > COST_MAP.md

Inputs (paths relative to mrv2_ctx_20261105/):
  costmap_20261107/run_20261111r2/analysis/cells.csv          r2 server measurements (2 launches per config)
  costmap_20261107/server_cmp/run_srv/evidence/costmap_out/compare_arms.json   server comparison (3 + 3 launches)
  kernel_probe_20261117/server_cmp/m32_projection.json        projection from isolated GEMM timings (not measured)
"""

import csv
import json
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CELLS = ROOT / "costmap_20261107/run_20261111r2/analysis/cells.csv"
ARMS = ROOT / "costmap_20261107/server_cmp/run_srv/evidence/costmap_out/compare_arms.json"
PROJ = ROOT / "kernel_probe_20261117/server_cmp/m32_projection.json"
CONFIGS = ["OFF", "Z", "K1", "K3", "K5"]
R_ASSUMED = 0.76


def shape_key(bs, ctx):
    return (int(bs), int(ctx))


def label(bs, ctx):
    return f"b{bs}·{int(ctx) // 1024}k"


def r2_means():
    vals = defaultdict(lambda: defaultdict(list))
    for row in csv.DictReader(open(CELLS)):
        if row["valid"] != "True":
            continue
        k = (shape_key(row["bs"], row["ctx"]), row["config"])
        vals[k]["step"].append(float(row["step_period_ms"]))
        vals[k]["tok"].append(float(row["delivered_ms_per_token"]))
        vals[k]["acc"].append(float(row["acceptance_rate"]) if row["acceptance_rate"] else None)
    return {k: {m: v for m, v in d.items()} for k, d in vals.items()}


def mean(xs):
    xs = [x for x in xs if x is not None]
    return sum(xs) / len(xs) if xs else None


def table(means, metric, fmt):
    shapes = sorted({s for s, _ in means})
    out = ["| shape | " + " | ".join(CONFIGS) + " |", "|---|" + "---:|" * len(CONFIGS)]
    for s in shapes:
        cells = []
        for c in CONFIGS:
            m = mean(means.get((s, c), {}).get(metric, []))
            cells.append(fmt.format(m) if m is not None else "—")
        out.append(f"| {label(*s)} | " + " | ".join(cells) + " |")
    return "\n".join(out)


def m32_rows(means):
    arms = json.load(open(ARMS))["cells"]
    proj = json.load(open(PROJ))["rows"]
    out = [
        "| shape | config | M | r2 step (ms, measured) | with (16, 32] config (ms) | source |",
        "|---|---|---:|---:|---:|---|",
    ]
    for row in proj:
        if not row["in_range"]:
            continue
        bs, ctx, cfg = row["bs"], row["ctx"], row["config"]
        r2 = mean(means[(shape_key(bs, ctx), cfg)]["step"])
        key = f"grid_b{bs}_c{ctx}"
        if cfg == "K1" and key in arms and arms[key]["status"] == "evaluated":
            p = mean(arms[key]["step_ms"]["P"])
            src = "**measured** (server comparison, 3 launches)"
        else:
            p = row["step_proj_scaled_ms"]
            src = f"*projection*, assumes r = {R_ASSUMED}"
        out.append(f"| {label(bs, ctx)} | {cfg} | {row['m']} | {r2:.2f} | {p:.2f} | {src} |")
    return "\n".join(out)


def main():
    means = r2_means()
    print("# K cost map — Gemma-4 31B FP8, MRv2, one H100 NVL (r2, 2026-11-11)\n")
    print("Generated by `public_20261119/build_cost_map.py` from committed raw outputs; do not edit by hand.\n")
    print("Configs: `OFF` = no drafter · `Z` = drafter loaded, K = 0 every step · `K1/K3/K5` = static K. "
          "Each value is the mean of two server launches (random-token prompts, `ignore_eos`, 640 output tokens). "
          "Every K-to-K difference and its launch spread is in `costmap_20261107/run_20261111r2/analysis/pairs.csv`.\n")
    print("## Step period (ms, measured)\n")
    print(table(means, "step", "{:.2f}"))
    print("\n## Delivered ms per token (measured; depends on acceptance)\n")
    print(table(means, "tok", "{:.3f}"))
    print("\n## Acceptance rate (measured)\n")
    print(table(means, "acc", "{:.3f}"))
    print("\n## Cells at M = 32 with #66852's (16, 32] FP8 GEMM config\n")
    print("Only target steps with 16 < M ≤ 32 take this branch. `K1 · b16` was **measured** on the server "
          "(`costmap_20261107/server_cmp/run_srv/`). Every other row is a **projection**: r2's step minus the "
          f"isolated-GEMM saving × r, with r = {R_ASSUMED} an assumption taken from one r2 observation. "
          "The server comparison saw 0.84–0.91 of the isolated saving for K1 · b16; that ratio was not measured "
          "for the other rows, so the assumption is kept.\n")
    print(m32_rows(means))


if __name__ == "__main__":
    main()
